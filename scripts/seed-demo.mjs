function hashSeed(value) {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function createRandom(seed) {
  let state = hashSeed(seed);
  return function nextRandom() {
    state += 0x6d2b79f5;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

function pickWeighted(items, random) {
  const total = items.reduce((sum, item) => sum + item.weight, 0);
  let target = random() * total;
  for (const item of items) {
    target -= item.weight;
    if (target <= 0) return item;
  }
  return items.at(-1);
}

function startOfUtcDay(date) {
  return new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
}

function addDays(date, days) {
  return new Date(date.getTime() + days * MS_PER_DAY);
}

function addCalendarYears(date, years) {
  return new Date(Date.UTC(date.getUTCFullYear() + years, date.getUTCMonth(), date.getUTCDate()));
}

function secondsIntoDay(random) {
  return Math.floor(random() * MS_PER_DAY);
}

function clickCountForDay(profile, day, dayIndex, random) {
  const weekend = day.getUTCDay() === 0 || day.getUTCDay() === 6;
  const zeroChance = Math.min(0.94, profile.zeroChance + (weekend ? 0.06 : 0));
  const roll = random();

  let count = 0;
  if (roll < zeroChance) {
    count = 0;
  } else if (roll < zeroChance + profile.singleChance) {
    count = 1;
  } else {
    count = 2 + Math.floor(Math.pow(random(), 1.8) * profile.maxBurst);
  }

  if (random() < profile.campaignChance) {
    count += 4 + Math.floor(random() * profile.campaignBurst);
  }

  if (dayIndex % 365 === 0 && dayIndex > 0) {
    count += 2 + Math.floor(random() * 4);
  }

  return count;
}

function buildClickRow(linkCode, shortLinkId, occurredAt, random, clickIndex, profile) {
  const country = pickWeighted(countries, random);
  const agent = pickWeighted(userAgents, random);
  const referrer = pickWeighted(referrers, random).value;
  const visitorIndex = Math.floor(random() * profile.visitorPool);
  const ipAddress = country.ipPrefix ? `${country.ipPrefix}.${1 + Math.floor(random() * 240)}` : null;
  const visitorKey = country.country ?? "unknown";

  return {
    shortLinkId,
    occurredAt,
    referrer,
    userAgent: agent.value,
    browser: agent.browser,
    device: agent.device,
    country: country.country,
    region: country.region,
    ipAddress,
    ipHash: ipAddress ? `demo-ip:${ipAddress}` : null,
    visitorHash: `demo-visitor:${linkCode}:${visitorKey}:${visitorIndex}:${clickIndex % 11}`
  };
}

function buildClicksForLink(linkDefinition, shortLinkId, startDate, endDate) {
  const random = createRandom(`${linkDefinition.code}:${startDate.toISOString()}:${endDate.toISOString()}`);
  const rows = [];
  let day = startDate;
  let dayIndex = 0;

  while (day <= endDate) {
    const count = clickCountForDay(linkDefinition.profile, day, dayIndex, random);
    for (let clickIndex = 0; clickIndex < count; clickIndex += 1) {
      rows.push(
        buildClickRow(
          linkDefinition.code,
          shortLinkId,
          new Date(day.getTime() + secondsIntoDay(random)),
          random,
          rows.length,
          linkDefinition.profile
        )
      );
    }
    day = addDays(day, 1);
    dayIndex += 1;
  }

  return rows.sort((left, right) => left.occurredAt.getTime() - right.occurredAt.getTime());
}

async function createClicks(rows) {
  for (let index = 0; index < rows.length; index += CLICK_BATCH_SIZE) {
    await prisma.clickEvent.createMany({
      data: rows.slice(index, index + CLICK_BATCH_SIZE)
    });
  }
}

async function seedTags() {
  const tagRows = new Map();
  for (const tag of tags) {
    const row = await prisma.tag.upsert({
      where: { slug: tag.slug },
      update: {
        name: tag.name,
        color: tag.color
      },
      create: tag
    });
    tagRows.set(tag.slug, row);
  }
  return tagRows;
}

async function seedDemoLink(linkDefinition, tagRows, admin, fiveYearsAgo, today) {
  const startDate = addDays(fiveYearsAgo, linkDefinition.startOffsetDays ?? 0);
  const endDate = linkDefinition.stopOffsetDays ? addDays(today, linkDefinition.stopOffsetDays) : today;
  const expiresAt = linkDefinition.expiresOffsetDays ? addDays(today, linkDefinition.expiresOffsetDays) : null;
  const archivedAt = linkDefinition.archivedOffsetDays ? addDays(today, linkDefinition.archivedOffsetDays) : null;
  const createdById = admin?.id ?? null;

  const link = await prisma.shortLink.upsert({
    where: { code: linkDefinition.code },
    update: {
      destinationUrl: linkDefinition.destinationUrl,
      title: linkDefinition.title,
      description: linkDefinition.description,
      notes: linkDefinition.notes,
      enabled: linkDefinition.enabled ?? true,
      archivedAt,
      expiresAt,
      maxClicks: null,
      passwordHash: null,
      createdAt: startDate,
      createdById,
      clickCount: 0,
      lastClickedAt: null
    },
    create: {
      code: linkDefinition.code,
      destinationUrl: linkDefinition.destinationUrl,
      title: linkDefinition.title,
      description: linkDefinition.description,
      notes: linkDefinition.notes,
      enabled: linkDefinition.enabled ?? true,
      archivedAt,
      expiresAt,
      createdAt: startDate,
      createdById
    }
  });

  await prisma.shortLinkTag.deleteMany({ where: { shortLinkId: link.id } });
  await prisma.shortLinkTag.createMany({
    data: linkDefinition.tags.map((slug) => ({
      shortLinkId: link.id,
      tagId: tagRows.get(slug).id
    })),
    skipDuplicates: true
  });

  await prisma.clickEvent.deleteMany({ where: { shortLinkId: link.id } });
  const clickRows = buildClicksForLink(linkDefinition, link.id, startDate, endDate);
  await createClicks(clickRows);

  await prisma.shortLink.update({
    where: { id: link.id },
    data: {
      clickCount: clickRows.length,
      lastClickedAt: clickRows.at(-1)?.occurredAt ?? null
    }
  });

  const activeDays = Math.floor((endDate.getTime() - startDate.getTime()) / MS_PER_DAY) + 1;
  const clickedDays = new Set(clickRows.map((row) => row.occurredAt.toISOString().slice(0, 10))).size;
  return {
    code: link.code,
    id: link.id,
    clicks: clickRows.length,
    activeDays,
    clickedDays,
    zeroDays: activeDays - clickedDays,
    firstClickAt: clickRows[0]?.occurredAt ?? null,
    lastClickAt: clickRows.at(-1)?.occurredAt ?? null
  };
}

async function main() {
  if (!process.env.DATABASE_URL) {
    throw new Error("DATABASE_URL is required to seed demo data.");
  }

  const today = startOfUtcDay(new Date());
  const fiveYearsAgo = addCalendarYears(today, -5);
  const [tagRows, admin] = await Promise.all([
    seedTags(),
    prisma.user.findFirst({ orderBy: { createdAt: "asc" }, select: { id: true, email: true } })
  ]);

  const results = [];
  for (const linkDefinition of demoLinks) {
    results.push(await seedDemoLink(linkDefinition, tagRows, admin, fiveYearsAgo, today));
  }

  console.log(`Demo seed complete${admin ? ` for ${admin.email}` : ""}.`);
  for (const result of results) {
    console.log(
      `/${result.code}: ${result.clicks} clicks over ${result.activeDays} days ` +
        `(${result.clickedDays} clicked, ${result.zeroDays} zero), id ${result.id}`
    );
  }
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
